"""Generate/check immutable model logic from independently reconciled exports."""
from pathlib import Path
import argparse
import hashlib

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/neural_24_64_64_4'


def generated_source():
    def words(name):
        return [int(line,16) for line in (ASSETS/name).read_text().splitlines()
                if line and not line.startswith('//')]
    image=words('bram_unified_weights.mem')
    rebuilt=[]
    for layer in range(1,4):
        rebuilt.extend(words(f'bram_w{layer}.mem'))
        rebuilt.extend(words(f'bram_b{layer}.mem'))
    assert image==rebuilt and len(image)==6020
    assert all(0<=word<65536 for word in image)
    digest=hashlib.sha256(b''.join(word.to_bytes(2,'little') for word in image)).hexdigest()
    header=f'''// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/generate_neural_logic_rom.py; do not edit constants.
// Model SHA256 (little-endian words): {digest}
// Immutable standard-cell logic. Host validation never changes coefficients.
`default_nettype none
module igor_parameter_logic(input wire clk,rst_n,enable,write_enable,
 input wire [12:0] address,input wire [15:0] unused_write_data,unused_write_mask,
 output wire signed [15:0] read_data,read_even,read_odd);
reg [31:0] decoded,pair_q;
reg odd_q,valid_q;
always @* begin
 case(address[12:1])
'''
    body=''.join(f"  12'd{i//2}: decoded=32'h{image[i+1]:04x}{image[i]:04x};\n"
                 for i in range(0,len(image),2))
    footer='''  default: decoded=0;
 endcase
end
always @(posedge clk or negedge rst_n) begin
 if(!rst_n) begin pair_q<=0;odd_q<=0;valid_q<=0;end
 else if(enable && !write_enable) begin
  pair_q<=decoded;odd_q<=address[0];valid_q<=address<6020;
 end
end
assign read_even=valid_q ? pair_q[15:0]:16'd0;
assign read_odd=valid_q ? pair_q[31:16]:16'd0;
assign read_data=odd_q ? read_odd:read_even;
endmodule
`default_nettype wire
'''
    return header+body+footer


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    target=ROOT/'src/igor_parameter_logic.v'
    source=generated_source()
    if args.check:
        if target.read_text()!=source:raise SystemExit('Generated model logic is stale')
        print('PASS: all 6020 immutable parameters match layer exports')
    else:
        target.write_text(source)
